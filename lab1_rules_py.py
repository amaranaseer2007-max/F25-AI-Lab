def evaluate_application(score, documents_complete,
                         attendance, conduct_satisfactory):

    reasons = []

    if score < 70:
        reasons.append("Score is below 70")

    if not documents_complete:
        reasons.append("Documents are incomplete")

    if attendance < 75:
        reasons.append("Attendance is below 75%")

    if not conduct_satisfactory:
        reasons.append("Conduct is unsatisfactory")

    if reasons:
        return "FAIL", "; ".join(reasons)

    return "PASS", "All four conditions are satisfied"


test_cases = [
    ("Case 1", 85, True, 90, True, "PASS"),
    ("Case 2", 85, True, 70, True, "FAIL"),
    ("Case 3", 85, True, 90, False, "FAIL"),
    ("Case 4", 70, True, 75, True, "PASS")
]

for name, score, docs, attendance, conduct, expected in test_cases:

    actual, reason = evaluate_application(
        score, docs, attendance, conduct
    )

    print("\n", name)
    print("Input:", score, docs, attendance, conduct)
    print("Expected:", expected)
    print("Actual:", actual)
    print("Reason:", reason)
    print("Test status:",
          "PASS" if actual == expected else "FAIL")