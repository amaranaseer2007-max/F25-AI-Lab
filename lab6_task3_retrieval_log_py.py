from lab6_search import Retriever

documents = [
    {"id": "doc1", "text": "AI helps doctors support medical diagnosis."},
    {"id": "doc2", "text": "Machine learning learns patterns from data."},
    {"id": "doc3", "text": "Deep learning uses neural networks."},
    {"id": "doc4", "text": "Students must submit assignments before deadlines."},
    {"id": "doc5", "text": "Teachers may approve extensions for valid reasons."}
]

retriever = Retriever(documents)
print("Retriever ready!")

relevant_docs = {
    "How does AI help doctors?": "doc1",
    "What is machine learning?": "doc2",
    "What does deep learning use?": "doc3",
    "When should students submit assignments?": "doc4"
}

hits = 0
mrr_total = 0

for query, relevant_id in relevant_docs.items():
    results = retriever.search(query, k=3)

    for rank, (record, score) in enumerate(results, start=1):
        if record["id"] == relevant_id:
            hits += 1
            mrr_total += 1 / rank
            break

print("Hit@3:", round(hits / len(relevant_docs), 3))
print("MRR@3:", round(mrr_total / len(relevant_docs), 3))

