from lab6_search import Retriever

documents = [
    {"id": "doc1", "text": "Artificial Intelligence helps doctors analyze medical information."},
    {"id": "doc2", "text": "Machine learning learns patterns from training data."},
    {"id": "doc3", "text": "Deep learning uses multi-layer neural networks."},
    {"id": "doc4", "text": "Students must submit assignments before the deadline."},
    {"id": "doc5", "text": "Teachers may approve extensions for valid reasons."}
]

queries = [
    ("How does AI help doctors?", "doc1"),
    ("What learns patterns from data?", "doc2"),
    ("What technology uses neural networks?", "doc3"),
    ("When should students submit assignments?", "doc4")
]

retriever = Retriever(documents, backend="tfidf")

hits = 0
reciprocal_ranks = []

for query, correct_id in queries:
    results = retriever.search(query, k=3)

    result_ids = [record["id"] for record, score in results]

    if correct_id in result_ids:
        hits += 1
        rank = result_ids.index(correct_id) + 1
        reciprocal_ranks.append(1 / rank)
    else:
        reciprocal_ranks.append(0)

hit_at_3 = hits / len(queries)
mrr_at_3 = sum(reciprocal_ranks) / len(queries)

print("Hit@3:", round(hit_at_3, 3))
print("MRR@3:", round(mrr_at_3, 3))